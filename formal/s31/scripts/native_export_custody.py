"""Local-process byte custody for the bounded Zig structural graph exporter.

This pins the direct export/build/parser entry points and checks that the
corpus file passed to Zig still contains the exact generated bytes afterward.
It assumes no concurrent same-user writer temporarily swaps that file while
the child reads it. It proves neither binary provenance nor compiler semantics.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PINNED_EXPORT_SOURCES = {
    "src/frontends/s31/tests/acceptance/compiler_correspondence/native_structural_witness_corpus.zig":
        "b4c34578e02a7194054e421e7678351b21897c4dfa3fc879749326dcb78bd10a",
    "src/frontends/s31/build.zig":
        "56992444df23af72e381e7fafcd5763fa908f1f9685e7fb4aad832488d20942a",
    "src/frontends/s31/build.zig.zon":
        "1ea6533b581189198d45471db2ed9d6fa9e84441a1be8c32865c1a616a12f911",
    "src/frontends/s31/mod.zig":
        "6eceaf3ade2233a5cad657e908a441154e348fda045999411dd339ac4b401de9",
    "src/frontends/s31/language/relation.zig":
        "5ff5314d5c447998fb1ed2ebfe1f9438a077501254620ac42a3e195be68c0e63",
}


def check_export_entry_sources(root: Path = ROOT) -> None:
    """Reject an unreviewed change in five direct export entry files."""
    for path, wanted in PINNED_EXPORT_SOURCES.items():
        try:
            actual = hashlib.sha256((root / path).read_bytes()).hexdigest()
        except OSError as exc:
            raise ValueError("native export custody: source unavailable: " + path) from exc
        if actual != wanted:
            raise ValueError("native export custody: source changed; review export path: " + path)


def check_corpus_bytes(corpus_bytes: bytes, raw: dict[str, bytes]) -> None:
    """Check the generated child input contains the snapshotted JSON strings."""
    try:
        corpus = json.loads(corpus_bytes)
    except (UnicodeError, ValueError) as exc:
        raise ValueError("native export custody: malformed child corpus") from exc
    if (type(corpus) is not dict or corpus.get("schema") !=
            "s31-structural-m31-native-witness-corpus-v1" or
            type(corpus.get("cases")) is not list or len(corpus["cases"]) != 1):
        raise ValueError("native export custody: child corpus roster differs")
    item = corpus["cases"][0]
    if type(item) is not dict:
        raise ValueError("native export custody: child corpus case malformed")
    for name in ("relation", "assignment"):
        if item.get(name) != raw[name].decode("utf-8"):
            raise ValueError("native export custody: " + name + " bytes differ")


def check_corpus_file(path: Path, planned_bytes: bytes) -> None:
    """Reject even semantically inert changes to the child input path."""
    if path.read_bytes() != planned_bytes:
        raise ValueError("native export custody: child corpus changed during export")
