//! Experimental P05 verifier-owned claim roster derivation.
//!
//! Call only after `core.verifier.verifyBorrowedExWithProofCapture` succeeds:
//! the scheme, AIR handles, proof sampled values, and capture must all be the
//! same objects used by that accepted verification. This module checks their
//! exact geometry and ownership; it does not independently prove OOD values.
const std = @import("std");
const core = @import("stwo_core");

const QM31 = core.fields.qm31.QM31;
const Point = core.circle.CirclePointQM31;
const PcsConfigV2 = core.pcs.config_v2.PcsConfigV2;
const Component = core.air.components.Component;
const AcceptedValues = core.pcs.TreeVec([][]QM31);

pub const Claim = struct {
    tree_index: usize,
    column_index: usize,
    sample_index: usize,
    source_log_size: u32,
    point: Point,
    value: QM31,
};

/// Recompute the exact four-tree mask and column roster from the accepted
/// scheme and AIR handles, and tie every captured claim to the accepted proof
/// values. The composition tree is generated by the same split/count and
/// single-point rule as pinned `core/verifier.zig:appendCompositionMaskTree`.
/// The caller must supply the verifier's *accepted* objects; this function
/// cannot turn arbitrary caller-built objects into an accepted proof.
pub fn derive(
    comptime H: type,
    allocator: std.mem.Allocator,
    pcs: PcsConfigV2,
    scheme: anytype,
    handles: []const Component,
    accepted_values: AcceptedValues,
    capture: *const core.verifier.ProofCapture(H),
    include_all_preprocessed_columns: bool,
) ![]Claim {
    const trees = scheme.trees.items;
    // The proposed ensemble covers every committed source column, including
    // fixed columns unused by a particular AIR mask.
    if (!include_all_preprocessed_columns or
        !std.meta.eql(scheme.revision_config, pcs))
        return error.InvalidP05VerifierRoster;
    if (trees.len != 4 or capture.commitments.len != 4 or
        capture.column_log_sizes.len != 4 or capture.sampled_points.len != 4 or
        accepted_values.items.len != 4)
        return error.InvalidP05VerifierRoster;
    if (handles.len == 0) return error.InvalidP05VerifierRoster;
    const components = core.air.components.Components{
        .components = handles,
        .n_preprocessed_columns = trees[0].column_log_sizes.len,
    };
    const split = components.compositionLogSplit() catch
        return error.InvalidP05VerifierRoster;
    const composition_log = components.compositionLogDegreeBound();
    const component_mask_log = core.verifier_types.compositionMaskLogSize(
        composition_log,
        split,
    ) orelse return error.InvalidP05VerifierRoster;
    const lifted_mask_log = std.math.sub(
        u32,
        pcs.trace_lifting_log_size,
        pcs.fri_config.log_blowup_factor,
    ) catch return error.InvalidP05VerifierRoster;
    const max_mask_log = @max(component_mask_log, lifted_mask_log);
    const oods_point = core.circle.secureFieldPointFromRandomSeedChecked(
        capture.oods_seed,
    ) catch return error.InvalidP05VerifierRoster;
    var masks = components.maskPoints(
        allocator,
        oods_point,
        max_mask_log,
        include_all_preprocessed_columns,
    ) catch return error.InvalidP05VerifierRoster;
    defer masks.deinitDeep(allocator);
    if (masks.items.len != 3) return error.InvalidP05VerifierRoster;
    var air_logs = components.columnLogSizes(allocator) catch
        return error.InvalidP05VerifierRoster;
    defer air_logs.deinitDeep(allocator);
    if (air_logs.items.len != 3) return error.InvalidP05VerifierRoster;
    const composition_count = core.verifier_types.compositionColumnCount(
        split,
        core.fields.qm31.SECURE_EXTENSION_DEGREE,
    ) orelse return error.InvalidP05VerifierRoster;

    var claim_count: usize = 0;
    for (trees, 0..) |tree, tree_index| {
        const logs = capture.column_log_sizes[tree_index];
        const captured_points = capture.sampled_points[tree_index];
        const proof_values = accepted_values.items[tree_index];
        if (!std.mem.eql(u8, &tree.root, &capture.commitments[tree_index]) or
            !std.mem.eql(u32, tree.column_log_sizes, logs) or
            captured_points.len != logs.len or proof_values.len != logs.len)
            return error.InvalidP05VerifierRoster;
        const expected_height = pcs.treeHeight(tree_index, logs) catch
            return error.InvalidP05VerifierRoster;
        if (tree.height != expected_height) return error.InvalidP05VerifierRoster;
        if (tree_index < 3) {
            if (!std.mem.eql(u32, air_logs.items[tree_index], logs) or
                masks.items[tree_index].len != logs.len)
                return error.InvalidP05VerifierRoster;
        } else {
            if (logs.len != composition_count) return error.InvalidP05VerifierRoster;
            for (logs) |log| {
                if (log != max_mask_log) return error.InvalidP05VerifierRoster;
            }
        }
        for (captured_points, proof_values, 0..) |points, values, column| {
            if (points.len != values.len or points.len == 0)
                return error.InvalidP05VerifierRoster;
            if (tree_index < 3) {
                const expected = masks.items[tree_index][column];
                if (points.len != expected.len) return error.InvalidP05VerifierRoster;
                for (points, expected) |got, want| {
                    if (!got.eql(want)) return error.InvalidP05VerifierRoster;
                }
            } else {
                if (points.len != 1 or !points[0].eql(oods_point))
                    return error.InvalidP05VerifierRoster;
            }
            claim_count = std.math.add(usize, claim_count, points.len) catch
                return error.InvalidP05VerifierRoster;
        }
    }
    if (capture.sampled_values.len != claim_count)
        return error.InvalidP05VerifierRoster;
    const out = try allocator.alloc(Claim, claim_count);
    errdefer allocator.free(out);
    var at: usize = 0;
    for (capture.column_log_sizes, capture.sampled_points, accepted_values.items, 0..) |logs, point_columns, value_columns, tree| {
        for (logs, point_columns, value_columns, 0..) |log, points, values, column| {
            for (points, values, 0..) |point, value, sample| {
                if (!capture.sampled_values[at].eql(value))
                    return error.InvalidP05VerifierRoster;
                out[at] = .{
                    .tree_index = tree,
                    .column_index = column,
                    .sample_index = sample,
                    .source_log_size = log,
                    .point = point,
                    .value = value,
                };
                at += 1;
            }
        }
    }
    return out;
}
