//! Candidate mapping from a source-generated Gate AIR roster to XDM04 slots.
//! No current production proof is dispatched through this mapping.
const std = @import("std");
const gate = @import("../gate_component_roster.zig");
const candidate = @import("cas05_candidate_v6.zig");

const Sha256 = std.crypto.hash.sha2.Sha256;
const domain = "S31-CAS05-SOURCE-AIR-ROSTER-V1\x00";

pub const Role = enum(u8) { preprocessed, base_trace, interaction_trace };

pub const Entry = struct {
    source_height: u16,
    source_column: u16,
    /// One OOD claim is expected per source M31 column, in source order.
    claim_index: u16,
    role: Role,
    /// For preprocessed entries this is the commitment column index.
    /// For trace entries this is the source-generated component proof index.
    owner_index: u32,
    local_column: u16,
    trace_log_size: u32,
};

pub const Profile = struct {
    largest_log_size: u32,
    height_count: u16,
    columns: [8]u16,
};

pub const Generated = struct {
    allocator: std.mem.Allocator,
    profile: Profile,
    entries: []Entry,
    sha256: [32]u8,

    pub fn deinit(self: *Generated) void {
        self.allocator.free(self.entries);
        self.* = undefined;
    }
};

/// Identity reconstructed outside the proof. The roster digest is deliberately
/// absent: `inspectGeneratedGateCandidate` derives it from the AIR manifest.
pub const TrustedIdentity = struct {
    sealed_key_bytes: []const u8,
    program_digest: [32]u8,
    public_abi_digest: ?[32]u8,
    circuit_hash: [32]u8,
    air_bundle_digest: [32]u8,
    public_words: [8]u32,
};

/// Audit-only bridge from a regenerated compiler manifest to the candidate
/// admission gate. Current Gate geometry fails before this can inspect a
/// proof. A forged caller-supplied manifest has no authority; the installed
/// verifier must regenerate it from source and selected AIR.
pub fn inspectGeneratedGateCandidate(
    allocator: std.mem.Allocator,
    identity: TrustedIdentity,
    manifest: gate.Manifest,
    supplied_key_bytes: []const u8,
    statement_bytes: []const u8,
    proof_bytes: []const u8,
) !void {
    var roster = try derive(allocator, manifest);
    defer roster.deinit();
    if (identity.sealed_key_bytes.len > 16 << 10) return error.CandidateMetadataTooLarge;
    var parsed = try std.json.parseFromSlice(candidate.CandidateKey, allocator, identity.sealed_key_bytes, .{
        .ignore_unknown_fields = false,
    });
    defer parsed.deinit();
    const profile = parsed.value.profile;
    if (profile.largest_log_size != roster.profile.largest_log_size or
        profile.height_count != roster.profile.height_count or
        !std.meta.eql(profile.columns, roster.profile.columns))
        return error.Cas05AirRosterProfileMismatch;
    return candidate.inspect(allocator, .{
        .sealed_key_bytes = identity.sealed_key_bytes,
        .program_digest = identity.program_digest,
        .public_abi_digest = identity.public_abi_digest,
        .circuit_hash = identity.circuit_hash,
        .air_bundle_digest = identity.air_bundle_digest,
        .source_air_roster_digest = roster.sha256,
        .public_words = identity.public_words,
    }, supplied_key_bytes, statement_bytes, proof_bytes);
}

/// The caller must pass the manifest regenerated by `gate.generate` from the
/// embedded source, selected AIR, and preprocessed circuit. This function
/// checks whether its geometry fits CAS05 v6, then defines a candidate
/// source/claim order. It does not construct or authenticate source columns,
/// and it does not establish that CAS05's polynomial relation is this AIR.
pub fn derive(allocator: std.mem.Allocator, manifest: gate.Manifest) !Generated {
    if (!std.mem.eql(u8, manifest.schema, "s31-component-roster-gate-v1") or
        manifest.components.len == 0 or
        manifest.components.len != manifest.claimed_sums)
        return error.InvalidCompilerRoster;

    var largest: u32 = 0;
    var smallest: u32 = 23;
    var entry_count: usize = 0;
    for (manifest.preprocessed_columns, 0..) |column, index| {
        if (column.commitment_index != index or column.log_size > 22 or
            column.rows != (@as(usize, 1) << @intCast(column.log_size)))
            return error.InvalidCompilerRoster;
        largest = @max(largest, column.log_size);
        smallest = @min(smallest, column.log_size);
        entry_count = try std.math.add(usize, entry_count, 1);
    }
    for (manifest.components, 0..) |component, index| {
        const component_columns = std.math.add(
            usize,
            component.base_trace_columns,
            component.interaction_trace_columns,
        ) catch return error.InvalidCompilerRoster;
        if (component.proof_index != index or component.claimed_sum_index != index or
            component.trace_log_size > 22 or
            component_columns == 0)
            return error.InvalidCompilerRoster;
        largest = @max(largest, component.trace_log_size);
        smallest = @min(smallest, component.trace_log_size);
        entry_count = try std.math.add(usize, entry_count, component.base_trace_columns);
        entry_count = try std.math.add(usize, entry_count, component.interaction_trace_columns);
    }
    if (entry_count == 0) return error.InvalidCompilerRoster;
    const height_count = largest - smallest + 1;
    if (height_count < 2 or height_count > 8) return error.UnsupportedCas05HeightRange;

    var profile = Profile{
        .largest_log_size = largest,
        .height_count = @intCast(height_count),
        .columns = [_]u16{0} ** 8,
    };
    if (entry_count > 8 * 64) return error.TooManyCas05Columns;
    const entries = try allocator.alloc(Entry, entry_count);
    errdefer allocator.free(entries);
    var at: usize = 0;
    for (0..height_count) |height| {
        const log_size = largest - @as(u32, @intCast(height));
        for (manifest.preprocessed_columns) |column| {
            if (column.log_size != log_size) continue;
            try add(entries, &at, &profile, @intCast(height), .preprocessed, @intCast(column.commitment_index), 0, log_size);
        }
        for (manifest.components) |component| {
            if (component.trace_log_size != log_size) continue;
            for (0..component.base_trace_columns) |local|
                try add(entries, &at, &profile, @intCast(height), .base_trace, component.proof_index, @intCast(local), log_size);
            for (0..component.interaction_trace_columns) |local|
                try add(entries, &at, &profile, @intCast(height), .interaction_trace, component.proof_index, @intCast(local), log_size);
        }
        if (profile.columns[height] == 0) return error.UnsupportedCas05HeightGap;
    }
    std.debug.assert(at == entry_count);
    var hasher = Sha256.init(.{});
    hasher.update(domain);
    hasher.update(&(try gate.digest(allocator, manifest)));
    hashInt(&hasher, profile.largest_log_size);
    hashInt(&hasher, profile.height_count);
    for (profile.columns[0..profile.height_count]) |count| hashInt(&hasher, count);
    for (entries) |entry| {
        hashInt(&hasher, entry.source_height);
        hashInt(&hasher, entry.source_column);
        hashInt(&hasher, entry.claim_index);
        hashInt(&hasher, @as(u8, @intFromEnum(entry.role)));
        hashInt(&hasher, entry.owner_index);
        hashInt(&hasher, entry.local_column);
        hashInt(&hasher, entry.trace_log_size);
    }
    var digest: [32]u8 = undefined;
    hasher.final(&digest);
    return .{ .allocator = allocator, .profile = profile, .entries = entries, .sha256 = digest };
}

fn add(
    entries: []Entry,
    at: *usize,
    profile: *Profile,
    height: u16,
    role: Role,
    owner: u32,
    local: u16,
    log_size: u32,
) !void {
    const count = &profile.columns[height];
    if (count.* >= 64) return error.TooManyCas05Columns;
    entries[at.*] = .{
        .source_height = height,
        .source_column = count.*,
        .claim_index = count.*,
        .role = role,
        .owner_index = owner,
        .local_column = local,
        .trace_log_size = log_size,
    };
    at.* += 1;
    count.* += 1;
}

fn hashInt(hasher: *Sha256, value: anytype) void {
    var bytes: [@sizeOf(@TypeOf(value))]u8 = undefined;
    std.mem.writeInt(@TypeOf(value), &bytes, value, .little);
    hasher.update(&bytes);
}

test "checked-in source-generated Gate AIR cannot fit CAS05 v6 heights" {
    const allocator = std.testing.allocator;
    const fixture = @embedFile("../../tests/python/security/fixtures/effects_gate_ownership/gate-component-roster.json");
    var parsed = try std.json.parseFromSlice(gate.Manifest, allocator, fixture, .{ .ignore_unknown_fields = false });
    defer parsed.deinit();
    try std.testing.expectError(error.UnsupportedCas05HeightRange, derive(allocator, parsed.value));
    try std.testing.expectError(error.UnsupportedCas05HeightRange, inspectGeneratedGateCandidate(
        allocator,
        .{
            .sealed_key_bytes = "{}",
            .program_digest = [_]u8{0} ** 32,
            .public_abi_digest = null,
            .circuit_hash = [_]u8{0} ** 32,
            .air_bundle_digest = [_]u8{0} ** 32,
            .public_words = [_]u32{0} ** 8,
        },
        parsed.value,
        "{}",
        "{}",
        "S31CAS05",
    ));
}

test "candidate roster has source and OOD claim slots only for adjacent supported heights" {
    const allocator = std.testing.allocator;
    const fixture = @embedFile("../../tests/python/security/fixtures/effects_gate_ownership/gate-component-roster.json");
    var parsed = try std.json.parseFromSlice(gate.Manifest, allocator, fixture, .{ .ignore_unknown_fields = false });
    defer parsed.deinit();
    var manifest = parsed.value;
    const components = [_]gate.Component{ manifest.components[0], manifest.components[1] };
    var adjusted = components;
    adjusted[0].trace_log_size = 6;
    adjusted[0].base_trace_columns = 1;
    adjusted[0].interaction_trace_columns = 1;
    adjusted[1].trace_log_size = 5;
    adjusted[1].base_trace_columns = 1;
    adjusted[1].interaction_trace_columns = 1;
    manifest.components = &adjusted;
    manifest.claimed_sums = 2;
    manifest.preprocessed_columns = &.{};
    var roster = try derive(allocator, manifest);
    defer roster.deinit();
    try std.testing.expectEqual(@as(u32, 6), roster.profile.largest_log_size);
    try std.testing.expectEqual(@as(u16, 2), roster.profile.height_count);
    try std.testing.expectEqual(@as(u16, 2), roster.profile.columns[0]);
    try std.testing.expectEqual(@as(u16, 2), roster.profile.columns[1]);
    try std.testing.expectEqual(Role.base_trace, roster.entries[0].role);
    try std.testing.expectEqual(Role.interaction_trace, roster.entries[1].role);
    try std.testing.expectEqual(@as(u16, 0), roster.entries[2].claim_index);

    const zero = [_]u8{0} ** 32;
    const zero_hex = std.fmt.bytesToHex(zero, .lower);
    const roster_hex = std.fmt.bytesToHex(roster.sha256, .lower);
    var key = candidate.CandidateKey{
        .schema = "s31-verification-key-cas05-candidate-v1",
        .pcs_mode = "cas05_sparse_v6",
        .transcript_version = "S31CAS06",
        .source_wire_version = "S31XDM04",
        .program_sha256 = &zero_hex,
        .circuit_hash = &zero_hex,
        .air_bundle_sha256 = &zero_hex,
        .source_air_roster_sha256 = &roster_hex,
        .profile = .{
            .largest_log_size = roster.profile.largest_log_size,
            .height_count = roster.profile.height_count,
            .log_blowup = 1,
            .query_count = 2,
            .columns = roster.profile.columns,
        },
    };
    const key_bytes = try std.json.Stringify.valueAlloc(allocator, key, .{});
    defer allocator.free(key_bytes);
    const identity = TrustedIdentity{
        .sealed_key_bytes = key_bytes,
        .program_digest = zero,
        .public_abi_digest = null,
        .circuit_hash = zero,
        .air_bundle_digest = zero,
        .public_words = [_]u32{0} ** 8,
    };
    // A matching compiler-derived key reaches statement parsing. The test
    // deliberately supplies no statement or proof, so it cannot accept.
    try std.testing.expectError(error.MissingField, inspectGeneratedGateCandidate(
        allocator,
        identity,
        manifest,
        key_bytes,
        "{}",
        "S31CAS05",
    ));
    key.profile.columns[0] = 1;
    const wrong_profile_bytes = try std.json.Stringify.valueAlloc(allocator, key, .{});
    defer allocator.free(wrong_profile_bytes);
    var wrong_profile_identity = identity;
    wrong_profile_identity.sealed_key_bytes = wrong_profile_bytes;
    try std.testing.expectError(error.Cas05AirRosterProfileMismatch, inspectGeneratedGateCandidate(
        allocator,
        wrong_profile_identity,
        manifest,
        wrong_profile_bytes,
        "{}",
        "S31CAS05",
    ));
    key.profile.columns[0] = 2;
    key.source_air_roster_sha256 = &zero_hex;
    const wrong_roster_bytes = try std.json.Stringify.valueAlloc(allocator, key, .{});
    defer allocator.free(wrong_roster_bytes);
    var wrong_roster_identity = identity;
    wrong_roster_identity.sealed_key_bytes = wrong_roster_bytes;
    try std.testing.expectError(error.InvalidInstalledKey, inspectGeneratedGateCandidate(
        allocator,
        wrong_roster_identity,
        manifest,
        wrong_roster_bytes,
        "{}",
        "S31CAS05",
    ));

    manifest.air_bundle_sha256 = "changed-compiled-air";
    var rebound = try derive(allocator, manifest);
    defer rebound.deinit();
    try std.testing.expect(!std.mem.eql(u8, &roster.sha256, &rebound.sha256));
    manifest.air_bundle_sha256 = parsed.value.air_bundle_sha256;

    adjusted[1].trace_log_size = 4;
    try std.testing.expectError(error.UnsupportedCas05HeightGap, derive(allocator, manifest));
    adjusted[1].trace_log_size = 6;
    try std.testing.expectError(error.UnsupportedCas05HeightRange, derive(allocator, manifest));
    adjusted[1].trace_log_size = 5;
    adjusted[1].base_trace_columns = 65;
    try std.testing.expectError(error.TooManyCas05Columns, derive(allocator, manifest));
}
