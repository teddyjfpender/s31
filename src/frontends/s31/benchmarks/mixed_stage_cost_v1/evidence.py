SCHEMA = "s31-mixed-stage-cost-v1-phase-root"
EXCLUDED_FROM_PHASE = {"phase-root.json", "audit.json", "corpus.json", "model.json",
                       "evaluation.json"}


def load_json(path: Path) -> dict:
    value = json.loads(path.read_bytes(), object_pairs_hook=unique_object)
    if type(value) is not dict:
        raise ValueError(f"expected JSON object: {path}")
    return value


def zig_cache_path(variable: str, default: Path) -> Path:
    path = Path(os.environ.get(variable) or default)
    # The Zig build subprocess runs from ROOT, regardless of the caller's cwd.
    return path if path.is_absolute() else ROOT / path


def disk_guard(out: Path, minimum: int) -> None:
    locations = (out, zig_cache_path("ZIG_LOCAL_CACHE_DIR", S31 / ".zig-cache"),
                 zig_cache_path("ZIG_GLOBAL_CACHE_DIR", Path.home() / ".cache/zig"),
                 Path(tempfile.gettempdir()))
    devices = set()
    for location in locations:
        path = location.resolve()
        while not path.exists():
            path = path.parent
        if path.stat().st_dev in devices:
            continue
        devices.add(path.stat().st_dev)
        if shutil.disk_usage(path).free < minimum:
            raise ValueError(f"mixed stage native unit requires {minimum} free bytes on {path}")


def bins(directory: Path, count: int) -> dict[str, Path]:
    base = directory / "mixed/bin"
    prefix = f"s31-mixed_stage_cost_v1_n{count}-mixed-general-"
    return {"prover": base / (prefix + "prover"),
            "verifier": base / (prefix + "native-verifier"),
            "inspector": base / (prefix + "manifest")}


def materialize(directory: Path, count: int, cfg: dict, expected: dict) -> None:
    directory.mkdir(parents=True, exist_ok=False)
    (directory / "assignments").mkdir()
    (directory / "statements").mkdir()
    for index in range(cfg["assignments_per_call_count"]):
        source_bytes, assignment, statement = case(count, index, cfg)
        if index == 0:
            (directory / "source.s31.json").write_bytes(source_bytes)
        if (sha(source_bytes) != expected["source_sha256"] or
                sha(assignment) != expected["assignment_sha256"][index] or
                sha(statement) != expected["typed_statement_sha256"][index]):
            raise ValueError("mixed cost generated bytes differ from frozen inventory")
        (directory / f"assignments/{index:02d}.json").write_bytes(assignment)
        (directory / f"statements/{index:02d}.json").write_bytes(statement)


def check_materialized(directory: Path, count: int, cfg: dict, expected: dict) -> None:
    if set(path.name for path in (directory / "assignments").iterdir()) != {
            f"{i:02d}.json" for i in range(cfg["assignments_per_call_count"])} or \
            set(path.name for path in (directory / "statements").iterdir()) != {
                f"{i:02d}.json" for i in range(cfg["assignments_per_call_count"])}:
        raise ValueError("mixed cost witness or statement roster is incomplete")
    for index in range(cfg["assignments_per_call_count"]):
        source_bytes, assignment, statement = case(count, index, cfg)
        if ((directory / "source.s31.json").read_bytes() != source_bytes or
                (directory / f"assignments/{index:02d}.json").read_bytes() != assignment or
                (directory / f"statements/{index:02d}.json").read_bytes() != statement or
                sha(source_bytes) != expected["source_sha256"] or
                sha(assignment) != expected["assignment_sha256"][index] or
                sha(statement) != expected["typed_statement_sha256"][index]):
            raise ValueError(f"mixed cost N={count}, witness={index}: frozen case changed")


def inspect(directory: Path, count: int, expected: dict) -> tuple[dict, bytes, bytes]:
    result = subprocess.run([str(bins(directory, count)["inspector"])],
                            capture_output=True, check=False)
    if result.returncode:
        raise ValueError("source-embedded mixed inspector failed")
    manifest = json.loads(result.stdout, object_pairs_hook=unique_object)
    if (manifest.get("schema") != "s31-mixed-component-inspection-general-v3" or
            manifest.get("profile") != "experimental-direct-mixed-general" or
            manifest.get("source_sha256") != expected["source_sha256"] or
            manifest.get("call_count") != count or
            manifest.get("slot_count") != expected["chip_slots"] or
            manifest.get("registry_manifest_sha256") != registry_digest(manifest) or
            type(manifest.get("circuit_identity_sha256")) is not str or
            len(manifest["circuit_identity_sha256"]) != 64):
        raise ValueError("mixed inspector differs from frozen source and chip schedule")
    return manifest, result.stdout, result.stderr


def build_split(split: str, out: Path, expected_protocol_sha256: str,
                anchor_commit: str, admission: dict | None = None) -> dict:
    out = out.resolve()
    protocol = check(expected_protocol_sha256, anchor_commit)
    cfg = design()
    if split not in ("train", "heldout"):
        raise ValueError("unsupported prospective split")
    if split == "heldout" and (type(admission) is not dict or
                              admission.get("schema") != "s31-mixed-stage-cost-v1-train-admission" or
                              admission.get("protocol_sha256") != expected_protocol_sha256):
        raise ValueError("held-out build requires the separately anchored train model")
    if out.exists():
        raise ValueError("mixed stage build output already exists; never resume a phase")
    disk_guard(out, protocol["minimum_available_disk_bytes_at_phase_start"])
    out.mkdir(parents=True, exist_ok=False)
    (out / "protocol-ref.json").write_bytes(canonical({
        "protocol_sha256": expected_protocol_sha256, "anchor_commit": anchor_commit,
        "split": split}))
    if split == "heldout":
        (out / "train-admission.json").write_bytes(canonical(admission))
    for count in cfg[f"{split}_call_counts"]:
        directory = out / f"n{count}"
        expected = protocol["inventory"][split][str(count)]
        materialize(directory, count, cfg, expected)
        disk_guard(out, protocol["minimum_available_disk_bytes_before_native_phase"])
        source_path = directory / "source.s31.json"
        command = ["zig", "build", "--build-file", str(S31 / "build.zig"), "install",
                   "-Doptimize=ReleaseFast", "-Ds31-version=2",
                   "-Ds31-lowering=direct-mixed-general", f"-Ds31-source={source_path}",
                   f"-Ds31-name=mixed_stage_cost_v1_n{count}", "-j1", "--prefix",
                   str(directory / "mixed")]
        start = time.perf_counter_ns()
        result = subprocess.run(command, capture_output=True, check=False, cwd=ROOT)
        end = time.perf_counter_ns()
        (directory / "build.stdout").write_bytes(result.stdout)
        (directory / "build.stderr").write_bytes(result.stderr)
        if result.returncode:
            raise RuntimeError(f"N={count} mixed package build failed; discard partial phase")
        manifest, stdout, stderr = inspect(directory, count, expected)
        (directory / "inspector.stdout").write_bytes(stdout)
        (directory / "inspector.stderr").write_bytes(stderr)
        binary_hashes = {name: sha(path.read_bytes()) for name, path in bins(directory, count).items()}
        build = {
            "schema": "s31-mixed-stage-cost-v1-build",
            "source_sha256": expected["source_sha256"],
            "registry_manifest_sha256": manifest["registry_manifest_sha256"],
            "circuit_identity_sha256": manifest["circuit_identity_sha256"],
            "binary_sha256": binary_hashes,
            "build_command": command,
            "build_start_monotonic_ns": start,
            "build_end_monotonic_ns": end,
            "build_wall_ns": end - start,
            "build_stdout_sha256": sha(result.stdout),
            "build_stderr_sha256": sha(result.stderr),
            "inspector_stdout_sha256": sha(stdout),
            "inspector_stderr_sha256": sha(stderr),
            "package_reused": False,
        }
        (directory / "build.json").write_bytes(canonical(build))
    return {"split": split, "sources_built": len(cfg[f"{split}_call_counts"])}


def check_build(directory: Path, count: int, expected: dict) -> dict:
    build = load_json(directory / "build.json")
    paths = bins(directory, count)
    manifest, stdout, stderr = inspect(directory, count, expected)
    command = ["zig", "build", "--build-file", str(S31 / "build.zig"), "install",
               "-Doptimize=ReleaseFast", "-Ds31-version=2",
               "-Ds31-lowering=direct-mixed-general",
               f"-Ds31-source={directory / 'source.s31.json'}",
               f"-Ds31-name=mixed_stage_cost_v1_n{count}", "-j1", "--prefix",
               str(directory / "mixed")]
    if (set(build) != {"schema", "source_sha256", "registry_manifest_sha256",
                       "circuit_identity_sha256", "binary_sha256", "build_command",
                       "build_start_monotonic_ns", "build_end_monotonic_ns",
                       "build_wall_ns", "build_stdout_sha256", "build_stderr_sha256",
                       "inspector_stdout_sha256", "inspector_stderr_sha256",
                       "package_reused"} or
            build["schema"] != "s31-mixed-stage-cost-v1-build" or
            build["source_sha256"] != expected["source_sha256"] or
            build["registry_manifest_sha256"] != manifest["registry_manifest_sha256"] or
            build["circuit_identity_sha256"] != manifest["circuit_identity_sha256"] or
            build["binary_sha256"] != {name: sha(path.read_bytes()) for name, path in paths.items()} or
            build["build_command"] != command or
            type(build["build_start_monotonic_ns"]) is not int or
            type(build["build_end_monotonic_ns"]) is not int or
            build["build_start_monotonic_ns"] < 0 or
            build["build_end_monotonic_ns"] <= build["build_start_monotonic_ns"] or
            build["build_wall_ns"] !=
                build["build_end_monotonic_ns"] - build["build_start_monotonic_ns"] or
            build["build_stdout_sha256"] != sha((directory / "build.stdout").read_bytes()) or
            build["build_stderr_sha256"] != sha((directory / "build.stderr").read_bytes()) or
            build["inspector_stdout_sha256"] != sha(stdout) or
            build["inspector_stderr_sha256"] != sha(stderr) or
            (directory / "inspector.stdout").read_bytes() != stdout or
            (directory / "inspector.stderr").read_bytes() != stderr or
            build["package_reused"] is not False):
        raise ValueError(f"N={count}: build duration, package, or source attestation differs")
    return build


def phase_file_digests(out: Path) -> list[dict[str, str]]:
    if any(path.is_symlink() for path in out.rglob("*")):
        raise ValueError("mixed stage raw phase cannot contain symlinks")
    files = sorted(path for path in out.rglob("*") if path.is_file() and
                   path.relative_to(out).as_posix() not in EXCLUDED_FROM_PHASE)
    return [{"path": path.relative_to(out).as_posix(), "sha256": sha(path.read_bytes())}
            for path in files]


def phase_root(out: Path, split: str, protocol_sha256: str) -> dict:
    entries = phase_file_digests(out)
    if not entries:
        raise ValueError("mixed stage phase has no raw evidence")
    return {"schema": SCHEMA, "split": split, "protocol_sha256": protocol_sha256,
            "file_count": len(entries), "content_root_sha256": sha(canonical(entries))}


def prove_split(split: str, out: Path, expected_protocol_sha256: str,
                anchor_commit: str, admission: dict | None = None) -> dict:
    out = out.resolve()
    protocol = check(expected_protocol_sha256, anchor_commit)
    cfg = design()
    if split not in ("train", "heldout"):
        raise ValueError("unsupported prospective split")
    if split == "heldout" and (type(admission) is not dict or
                              (out / "train-admission.json").read_bytes() != canonical(admission)):
        raise ValueError("held-out proving differs from frozen train admission")
    if not out.is_dir() or (out / "phase-root.json").exists() or \
            any((out / f"n{count}/trials").exists() for count in cfg[f"{split}_call_counts"]):
        raise ValueError("mixed stage proof evidence is absent or already started")
    if load_json(out / "protocol-ref.json") != {
            "protocol_sha256": expected_protocol_sha256, "anchor_commit": anchor_commit,
            "split": split}:
        raise ValueError("mixed stage phase protocol reference differs")
    disk_guard(out, protocol["minimum_available_disk_bytes_at_phase_start"])
    for count in cfg[f"{split}_call_counts"]:
        directory = out / f"n{count}"
        expected = protocol["inventory"][split][str(count)]
        check_materialized(directory, count, cfg, expected)
        check_build(directory, count, expected)
        paths = bins(directory, count)
        (directory / "trials").mkdir()
        for index in range(cfg["assignments_per_call_count"]):
            disk_guard(out, protocol["minimum_available_disk_bytes_before_native_phase"])
            measure(paths["prover"], paths["verifier"], paths["inspector"],
                    directory / f"assignments/{index:02d}.json",
                    directory / f"statements/{index:02d}.json",
                    directory / f"trials/{index:02d}")
    root = phase_root(out, split, expected_protocol_sha256)
    (out / "phase-root.json").write_bytes(canonical(root))
    return root


def changed_claim(original: bytes, leaf_index: int) -> bytes:
    value = json.loads(original, object_pairs_hook=unique_object)
    if (value.get("version") != 2 or type(value.get("leaves")) is not list or
            len(value["leaves"]) != 2 or
            type(value["leaves"][leaf_index].get("words")) is not list):
        raise ValueError("record v2 typed statement has wrong claim shape")
    value["leaves"][leaf_index]["words"][0] = \
        (value["leaves"][leaf_index]["words"][0] + 1) % ((1 << 31) - 1)
    return canonical(value)


def replay_trial(directory: Path, count: int, index: int, expected: dict,
                 build: dict, *, replay_native: bool) -> dict:
    trial = directory / f"trials/{index:02d}"
    report = load_json(trial / "report.json")
    proof = (trial / "proof.bin").read_bytes()
    statement = (trial / "statement.json").read_bytes()
    supplied = (directory / f"statements/{index:02d}.json").read_bytes()
    assignment = (directory / f"assignments/{index:02d}.json").read_bytes()
    paths = bins(directory, count)
    manifest = load_json(directory / "inspector.stdout")
    if (set(report) != {"schema", "external_native_verification_accepted", "source_sha256",
                        "registry_manifest_sha256", "circuit_identity_sha256", "binary_sha256",
                        "assignment_sha256", "typed_statement_sha256", "proof_sha256",
                        "proof_bytes", "prover_process_wall_ns",
                        "external_verifier_process_wall_ns", "first_verified_process_wall_ns",
                        "process_monotonic_ns", "prover_internal_stages_ns",
                        "engine_setup_preprocessing_ns", "engine_pow_ns", "raw_log_sha256"} or
            report["source_sha256"] != expected["source_sha256"] or
            report["registry_manifest_sha256"] != build["registry_manifest_sha256"] or
            report["circuit_identity_sha256"] != build["circuit_identity_sha256"] or
            report["binary_sha256"] != build["binary_sha256"] or
            report["assignment_sha256"] != expected["assignment_sha256"][index] or
            report["assignment_sha256"] != sha(assignment) or
            report["typed_statement_sha256"] != expected["typed_statement_sha256"][index] or
            report["typed_statement_sha256"] != sha(supplied) or
            statement != supplied or report["proof_sha256"] != sha(proof) or
            report["proof_bytes"] != len(proof) or
            report["raw_log_sha256"] != {
                name: sha((trial / name).read_bytes()) for name in (
                    "prover.stdout", "prover.stderr", "verifier.stdout", "verifier.stderr",
                    "inspector.stdout", "inspector.stderr")}
            or (trial / "inspector.stdout").read_bytes() !=
                (directory / "inspector.stdout").read_bytes() or
            (trial / "inspector.stderr").read_bytes() !=
                (directory / "inspector.stderr").read_bytes()):
        raise ValueError(f"N={count}/{index}: diagnostic differs from frozen artifacts")
    stages = parse_prover_stage((trial / "prover.stderr").read_bytes(), manifest,
                                proof, statement)
    if stages["stages_ns"] != report["prover_internal_stages_ns"]:
        raise ValueError("saved prover stage line differs from diagnostic report")
    components(report)
    if replay_native:
        result = subprocess.run([str(paths["verifier"]), str(trial / "proof.bin"),
                                 str(trial / "statement.json")], capture_output=True, check=False)
        if result.returncode:
            raise ValueError(f"N={count}/{index}: native proof replay rejected")
        for leaf in (0, 1):
            with tempfile.TemporaryDirectory() as temp:
                changed = Path(temp) / "changed-statement.json"
                changed.write_bytes(changed_claim(statement, leaf))
                result = subprocess.run([str(paths["verifier"]), str(trial / "proof.bin"),
                                         str(changed)], capture_output=True, check=False)
                if result.returncode == 0:
                    raise ValueError(f"N={count}/{index}: changed public claim accepted")
        if ((trial / "proof.bin").read_bytes() != proof or
                (trial / "statement.json").read_bytes() != statement or
                (directory / f"assignments/{index:02d}.json").read_bytes() != assignment or
                (directory / f"statements/{index:02d}.json").read_bytes() != supplied or
                {name: sha(path.read_bytes()) for name, path in paths.items()} !=
                build["binary_sha256"]):
            raise ValueError("native verifier changed proof, claim, witness, or executable")
    return report


def audit_split(out: Path, split: str, expected_protocol_sha256: str,
                protocol_anchor_commit: str, expected_phase_root_sha256: str,
                phase_anchor_commit: str, admission: dict | None = None) -> dict:
    out = out.resolve()
    protocol = check(expected_protocol_sha256, protocol_anchor_commit)
    cfg = design()
    if split not in ("train", "heldout"):
        raise ValueError("unsupported mixed cost split")
    if (out / "audit.json").exists() or (out / "corpus.json").exists():
        raise ValueError("mixed cost audit already exists; never re-audit in place")
    if split == "heldout" and (type(admission) is not dict or
                              (out / "train-admission.json").read_bytes() != canonical(admission)):
        raise ValueError("held-out audit differs from frozen train admission")
    root_path = out / "phase-root.json"
    saved_root = root_path.read_bytes()
    if saved_root != canonical(phase_root(out, split, expected_protocol_sha256)) or \
            sha(saved_root) != expected_phase_root_sha256:
        raise ValueError("raw mixed cost phase differs from externally anchored digest")
    anchor_path = ROOT / f"design/s31/measurements/language/mixed-stage-cost-v1-{split}-phase-anchor.json"
    anchor = anchored(anchor_path, phase_anchor_commit,
                      "s31-mixed-stage-cost-v1-phase-anchor")
    if subprocess.run(["git", "-C", str(ROOT), "merge-base", "--is-ancestor",
                       protocol_anchor_commit, phase_anchor_commit], check=False).returncode:
        raise ValueError("mixed cost phase anchor precedes protocol freeze")
    if split == "heldout" and subprocess.run(
            ["git", "-C", str(ROOT), "merge-base", "--is-ancestor",
             admission["model_anchor_commit"], phase_anchor_commit],
            check=False).returncode:
        raise ValueError("held-out phase anchor precedes frozen training model")
    if (anchor.get("schema") != "s31-mixed-stage-cost-v1-phase-anchor" or
            anchor.get("split") != split or
            anchor.get("protocol_sha256") != expected_protocol_sha256 or
            anchor.get("phase_root_sha256") != expected_phase_root_sha256):
        raise ValueError("mixed cost phase anchor differs from raw phase")
    if load_json(out / "protocol-ref.json") != {
            "protocol_sha256": expected_protocol_sha256,
            "anchor_commit": protocol_anchor_commit, "split": split}:
        raise ValueError("mixed cost protocol reference differs from phase")
    corpus = {"schema": "s31-mixed-stage-cost-v1-audited-corpus", "split": split,
              "protocol_sha256": expected_protocol_sha256,
              "phase_root_sha256": expected_phase_root_sha256,
              "host": protocol["host"], "compiler_sha256": protocol["compiler_sha256"],
              "engine_gitlink_commit": protocol["engine_gitlink_commit"],
              "inventory_sha256": protocol["inventory_sha256"], "records": []}
    for count in cfg[f"{split}_call_counts"]:
        directory = out / f"n{count}"
        expected = protocol["inventory"][split][str(count)]
        check_materialized(directory, count, cfg, expected)
        build = check_build(directory, count, expected)
        if set(path.name for path in (directory / "trials").iterdir()) != {
                f"{i:02d}" for i in range(cfg["assignments_per_call_count"])}:
            raise ValueError("mixed cost trial roster incomplete")
        trials = []
        for index in range(cfg["assignments_per_call_count"]):
            disk_guard(out, protocol["minimum_available_disk_bytes_before_native_phase"])
            trials.append(replay_trial(directory, count, index, expected, build,
                                       replay_native=True))
        corpus["records"].append({"call_count": count,
                                  "source_sha256": expected["source_sha256"],
                                  "build_wall_ns": build["build_wall_ns"],
                                  "trials": trials})
    if saved_root != canonical(phase_root(out, split, expected_protocol_sha256)):
        raise ValueError("raw mixed cost phase changed during native audit replay")
    (out / "corpus.json").write_bytes(canonical(corpus))
    audit = {"schema": "s31-mixed-stage-cost-v1-audit", "split": split,
             "phase_root_sha256": expected_phase_root_sha256,
             "corpus_sha256": sha((out / "corpus.json").read_bytes()),
             "native_verified_proofs": 4 * cfg["assignments_per_call_count"],
             "changed_input_and_result_rejected": True,
             "raw_build_and_process_endpoints_replayed": True,
             "source_assignment_statement_manifest_and_binary_hashes_replayed": True}
    (out / "audit.json").write_bytes(canonical(audit))
    return audit
