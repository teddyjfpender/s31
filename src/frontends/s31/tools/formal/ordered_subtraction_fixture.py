"""Render exact source/relation bytes for Lean's ordered-subtraction checker.

The expected parsed instructions are written independently in the Lean
template. A source or normalized-byte change must therefore be reviewed
against that template before the generated theorem can compile.
"""

from __future__ import annotations

import json
from pathlib import Path


def _lean_lines(data: str) -> str:
    if not data.isascii():
        raise ValueError("ordered subtraction fixture requires ASCII bytes")
    lines = data.splitlines(keepends=True)
    if "".join(lines) != data:
        raise ValueError("fixture did not preserve source bytes")
    return "(\n    " + " ++\n    ".join(json.dumps(line) for line in lines) + ")"


def render(source_path: Path) -> str:
    from src.frontends.s31.python.text_frontend import compile_file

    source = source_path.read_bytes().decode("ascii")
    program, _ = compile_file(source_path)
    normalized = json.dumps(program, indent=2, sort_keys=True, ensure_ascii=True) + "\n"
    wrong_relation = normalized.replace('"op": "sub"', '"op": "add"', 1)
    if wrong_relation == normalized:
        raise ValueError("ordered subtraction fixture lost its subtraction node")
    return f'''import S31.Gadgets.Functional.Correspondence.OrderedSubtractionBytes

/-! Generated by `scripts/s31_formal.py` from the checked-in `manual.s31`
source and the production text frontend's exact normalized JSON bytes.
The expected parsed DAG below is independently reviewed, not generated from
the compiler's node list. Do not edit this file directly. -/

namespace S31.Functional.Correspondence.GeneratedOrderedSubtractionRelease

open S31.Functional.SSATextBytes
open S31.Functional.Correspondence.OrderedSubtractionBytes

set_option maxRecDepth 8192
set_option maxHeartbeats 0

def sourceBytes : Token := token {_lean_lines(source)}

def normalizedBytes : Token := token {_lean_lines(normalized)}

def changedOperationBytes : Token := token {_lean_lines(wrong_relation)}

def expectedParsed : OrderedSubtractionBytes.Parsed :=
  {{ circuitName := token "release_sub4",
    inputName := token "x",
    outputName := token "result",
    wireNames := [token "x", token "_s31_i1_0", token "_s31_i1_1", token "result"],
    instructions := [
      {{ id := 1, lhs := 0, rhs := 0, op := .add }},
      {{ id := 2, lhs := 0, rhs := 1, op := .sub }},
      {{ id := 3, lhs := 2, rhs := 0, op := .sub }}],
    output := 3 }}

theorem source_bytes_exact :
    OrderedSubtractionBytes.parseBytes sourceBytes = some expectedParsed := by decide

theorem source_relation_bytes_exact :
    checkRelation sourceBytes normalizedBytes = some expectedParsed := by decide

theorem changed_normalized_operation_rejected :
    checkRelation sourceBytes changedOperationBytes = none := by decide

end S31.Functional.Correspondence.GeneratedOrderedSubtractionRelease
'''


def render_helper(source_path: Path) -> str:
    """Bind the functional helper spelling to the reviewed direct DAG."""
    from src.frontends.s31.python.text_frontend import compile_file

    source = source_path.read_bytes().decode("ascii")
    direct = source_path.with_name("manual.s31")
    helper_program, _ = compile_file(source_path)
    direct_program, _ = compile_file(direct)
    if helper_program != direct_program:
        raise ValueError("functional helper changed the normalized direct relation")
    reversed_source = source.replace("difference - a", "a - difference", 1)
    if reversed_source == source:
        raise ValueError("functional helper lost its final ordered subtraction")
    collided_source = source.replace("let result = affine", "let _s31_i1_0 = affine", 1)
    collided_source = collided_source.replace("    result\n}", "    _s31_i1_0\n}", 1)
    if (collided_source == source or "let result = affine" in collided_source or
            "    _s31_i1_0\n}" not in collided_source):
        raise ValueError("functional helper output collision fixture changed")
    return f'''import S31.Gadgets.Functional.Correspondence.OrderedSubtractionHelperBytes
import S31.Gadgets.Functional.Correspondence.GeneratedOrderedSubtractionRelease

/-! Generated by `scripts/s31_formal.py` from the checked-in functional
helper source. Its production normalized relation must equal `manual.s31`.
The independent Lean parser checks the actual helper bytes and statically
inlines the call. Do not edit this file directly. -/

namespace S31.Functional.Correspondence.GeneratedOrderedSubtractionHelper

open S31.Functional.SSATextBytes
open S31.Functional.Correspondence.GeneratedOrderedSubtractionRelease

set_option maxRecDepth 8192
set_option maxHeartbeats 0

def functionalBytes : Token := token {_lean_lines(source)}

def reversedFinalSubtractionBytes : Token :=
  token {_lean_lines(reversed_source)}

def collidingOutputBytes : Token :=
  token {_lean_lines(collided_source)}

theorem helper_relation_bytes_exact :
    OrderedSubtractionHelperBytes.checkRelation functionalBytes normalizedBytes =
      some expectedParsed := by decide

theorem reversed_final_subtraction_rejected :
    OrderedSubtractionHelperBytes.checkRelation reversedFinalSubtractionBytes
      normalizedBytes = none := by decide

theorem colliding_generated_wire_name_rejected :
    OrderedSubtractionHelperBytes.parseBytes collidingOutputBytes = none := by decide

/-- Static helper application has exactly the direct source meaning in every
M31 lane and therefore requires no additional arithmetic row. -/
theorem helper_direct_denotation_equal
    (input : OrderedSubtractionBytes.Lanes) :
    OrderedSubtractionHelperBytes.denotation functionalBytes input =
      OrderedSubtractionBytes.denotation sourceBytes input := by
  have hhelper := (OrderedSubtractionHelperBytes.checked_relation_bytes
    functionalBytes normalizedBytes expectedParsed helper_relation_bytes_exact).1
  have hdirect := (OrderedSubtractionBytes.checked_relation_bytes
    sourceBytes normalizedBytes expectedParsed source_relation_bytes_exact).1
  simp [OrderedSubtractionHelperBytes.denotation,
        OrderedSubtractionBytes.denotation, hhelper, hdirect]

end S31.Functional.Correspondence.GeneratedOrderedSubtractionHelper
'''
